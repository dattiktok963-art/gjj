static inline const char *sec_decrypt(const uint8_t *enc, size_t len, uint8_t key) {
    static __thread char ring[16][512];
    static __thread size_t ring_idx = 0;
    char *buf = ring[ring_idx++ & 15];
    volatile uint8_t vkey = key;
    for (size_t i = 0; i < len; ++i) {
        buf[i] = (char)(enc[i] ^ (vkey + (uint8_t)i));
    }
    buf[len] = '\0';
    return buf;
}

